"""Finite read-only legacy capture for an explicitly selected project.

The caller owns the repeatable-read PostgreSQL transaction, pinned directory
capabilities and stopped-source proof. This module never opens a catalog,
constructs runtime owners, enrolls records or writes source metadata. Scientific
shapes are admitted by their existing project/domain codecs. Missing observations
are reported; they are never replaced with invented history or regenerated bytes.
"""
import copy
from collections import deque
from datetime import datetime, timezone
import hashlib
import json
from types import SimpleNamespace

from workbench import Workbench, WorkbenchError
import project_data as data_codec
import project_material as material_codec
import project_history as history_codec
import project_producers as producer_codec
from projects import decode_retained_snapshot, manifest, decode as decode_manifest, relative_path
from project_files import file_id, MAX_FILE_BYTES

MAX_PAYLOAD = 40 * 1024 * 1024
MAX_RECORDS = 100000
ROOT_FAMILIES = {
    'records': 'workbench_record', 'responses': 'workbench_response',
    'preferences': 'workbench_preference', 'selections': 'saved_selection',
    'searches': 'saved_search', 'graphs': 'pipeline_graph',
    'recipe_drafts': 'recipe_definition', 'model_definitions': 'model_definition',
    'studies': 'study_history', 'runs': 'run_history', 'releases': 'dataset_release',
    'exposures': 'dataset_exposure', 'model_materials': 'model_material',
    'recipe_materials': 'recipe_material', 'runtime_materials': 'runtime_material',
}
PRODUCERS = {'generation': 'generation_history', 'grounded': 'grounded_history',
             'caption': 'caption_proposal_history', 'text_proposal': 'text_proposal_history'}
NAMESPACED = frozenset(material_codec.FAMILIES) | frozenset(history_codec.FAMILY_FORMATS) | frozenset(producer_codec.FAMILIES)


def _json(value):
    return json.loads(value) if isinstance(value, str) else copy.deepcopy(value)


def _missing(detail):
    raise WorkbenchError(detail, 'missing_source', 409)


class _ReadAccess:
    """An internal read-view guard, never an imported actor or grant."""
    def require(self, scope, *args, **kwargs):
        if scope != 'inspect':
            raise WorkbenchError('Extraction source views are read-only.', 'forbidden', 403)
    def audit(self, *args, **kwargs):
        raise WorkbenchError('Extraction cannot append source audit.', 'forbidden', 403)


class _Capture:
    def __init__(self, source):
        self.source, self.db = source, source.db
        self.origin = data_codec.identity(self.db.dataset_id)
        self.records, self.inventory, self.dependencies = {}, {}, {}
        self.blockers, self.warnings, self.working_files = [], [], []
        self.anchor = None
        self.queue, self.visited, self.queued = deque(), set(), set()
        self.snapshot_by_id = {}
        self.raw_cache = {}
        self.payload_gaps = []
        self.deleted_intents = set()
        self.session = SimpleNamespace(snapshot=source.snapshot, db=self.db,
            artifacts=source.artifacts, check=lambda: None)
        # Workbench and each metadata-view constructor only assign references;
        # none runs SQL, creates directories or constructs Dataset/Jobs/Runs.
        # Never call get/history: those public owners may enroll images.
        dataset = SimpleNamespace(db=self.db, lock=self.db.lock, access=_ReadAccess(),
            path=self.db.path, project_sources={}, project_availability=self._available)
        self.reader = Workbench(dataset)
        # Scientific metadata must use the caller's pinned catalog FD reader.
        self.reader.scientific._capture = lambda identity: self._catalog_source('field_sequence', identity)

    def locator(self, family, identity):
        if type(identity) is not str:
            raise WorkbenchError('Source identities must be exact strings.')
        bare = identity
        if family in NAMESPACED and identity.startswith(self.origin + '.'):
            bare = identity[len(self.origin) + 1:]
        if family in ('project_artifact', 'dataset_release', 'project_file', 'model_material',
                      'recipe_material', 'runtime_material', 'project_snapshot'):
            data_codec.sha(bare)
        else:
            data_codec.identity(bare)
        return self.origin + '.' + bare if family in NAMESPACED else bare

    def bare(self, family, identity):
        if family in NAMESPACED:
            prefix = self.origin + '.'
            if not identity.startswith(prefix):
                raise WorkbenchError('Source dependency belongs to another catalog.', 'unsupported', 409)
            return identity[len(prefix):]
        return identity

    def observe(self, family, identity, revision=None):
        key = family, self.locator(family, identity)
        previous = self.inventory.get(key)
        value = dict(family=key[0], id=key[1], revision=revision)
        if previous is not None and previous != value and revision is not None:
            raise WorkbenchError('Source inventory identity has conflicting revisions.', 'invalid', 409)
        if previous is None or revision is not None:
            if previous is None and len(self.inventory) >= MAX_RECORDS:
                raise WorkbenchError('Legacy source exceeds the supported finite inventory.', 'too_large', 413)
            self.inventory[key] = value
        return key

    def need(self, family, identity, parent=None, reason='required scientific dependency'):
        target = self.observe(family, identity)
        if parent is not None:
            source = dict(family=parent[0], id=parent[1])
            edge = dict(source=source, target=dict(family=target[0], id=target[1]), reason=reason)
            self.dependencies[(parent, target, reason)] = edge
        if target not in self.visited and target not in self.queued:
            self.queue.append(target);self.queued.add(target)
        return target

    def issue(self, key, code, detail, *, warning=False):
        value = dict(family=key[0], id=key[1], code=code, detail=str(detail)[:1000])
        destination = self.warnings if warning else self.blockers
        if value not in destination:
            destination.append(value)

    def add(self, record):
        key = record['family'], record['id']
        if key in self.records and self.records[key] != record:
            raise WorkbenchError('Two source owners disagree about the same retained fact.', 'invalid', 409)
        self.records[key] = copy.deepcopy(record)
        self.observe(*key)

    def intrinsic(self, parent, blob, *, preservation='unique', role='source', raw=None):
        sha, size = blob['sha256'], blob['bytes']
        data_codec.sha(sha)
        if type(size) is not int or not 0 <= size <= 2**63 - 1:
            raise WorkbenchError('Invalid source payload size.')
        declaration = dict(format='project_artifact_v1', sha256=sha, bytes=size)
        self.add(dict(family='project_artifact', id=sha, document=declaration))
        self.need('project_artifact', sha, parent, preservation + ':' + role)
        try:
            if raw is None:
                if sha in self.raw_cache:
                    raw = self.raw_cache[sha]
                elif size > MAX_PAYLOAD and hasattr(self.source, 'payload_fd'):
                    with self.source.payload_fd(sha, size) as handle:
                        descriptor = handle[0] if isinstance(handle, tuple) else handle
                        self.source.artifacts.publish_fd(descriptor, declaration, maximum_bytes=size)
                    return
                else:
                    raw = self.source.resolve_payload(sha, size)
            if type(raw) is not bytes or len(raw) != size or hashlib.sha256(raw).hexdigest() != sha:
                raise WorkbenchError('Original payload differs from its declared byte identity.', 'corrupt_payload', 409)
            self.source.artifacts.publish_bytes(raw, declaration, maximum_bytes=max(size, 1))
        except (OSError, WorkbenchError) as error:
            self.payload_gaps.append((parent, sha, 'missing_regenerable' if preservation == 'regenerable' else getattr(error, 'code', 'missing_payload'), role + ': ' + str(error), preservation))

    def raw(self, parent, raw, role, *, media='application/octet-stream', kind=None):
        blob = dict(sha256=hashlib.sha256(raw).hexdigest(), bytes=len(raw))
        self.raw_cache[blob['sha256']] = raw
        self.intrinsic(parent, blob, raw=raw, role=role)
        if kind is None:
            return blob
        return dict(artifact=dict(namespace=self.origin, sha256=blob['sha256']), media_type=media,
            kind=kind, role=role, preservation='unique', required_for=['inspect', 'release'])

    def _catalog_source(self, kind, identity):
        folder, name = {'audio': ('audio', 'source.wav'), 'field_sequence': ('field_sequence', 'source.zip')}[kind]
        return self.source.read_catalog(folder + '/' + identity + '/' + name, MAX_PAYLOAD)

    def _available(self, identity):
        row = self.db.execute('SELECT kind FROM workbench_records WHERE id=%s', (identity,)).fetchone()
        if row is None:
            return False
        try:
            self._catalog_source(row[0], identity)
            return True
        except (OSError, WorkbenchError):
            return False

    def _audit(self, target, actions, *, include_denied=False):
        values = []
        for row in self.db.execute('SELECT actor_id,action,target_json,details_json,result,created_at FROM access_audit WHERE target_json::jsonb=%s::jsonb ORDER BY created_at,id', (json.dumps(target),)):
            if row['action'] not in actions or row['result'] != 'success' and not include_denied:
                continue
            values.append(dict(actor_id=row['actor_id'], action=row['action'], target=_json(row['target_json']),
                details=_json(row['details_json']), result=row['result'],
                occurred_at=datetime.fromtimestamp(row['created_at'], timezone.utc).isoformat()))
        return values

    def discover(self):
        # Only identity/revision columns are read for unrelated global rows.
        for row in self.db.execute('SELECT id,revision FROM workbench_records ORDER BY id'):
            self.observe('workbench_record', row[0], row[1])
        for family, statement in (
            ('workbench_response', 'SELECT id,revision FROM workbench_responses ORDER BY id'),
            ('workbench_preference', 'SELECT id,revision FROM workbench_preferences ORDER BY id'),
            ('saved_selection', 'SELECT id,revision FROM saved_selections ORDER BY id'),
            ('saved_search', 'SELECT id,revision FROM saved_searches ORDER BY id'),
            ('pipeline_graph', 'SELECT id,revision FROM workspace_graphs ORDER BY id'),
            ('recipe_definition', 'SELECT id,revision FROM workspace_recipe_drafts ORDER BY id'),
            ('model_definition', 'SELECT id,revision FROM model_definition_drafts ORDER BY id'),
            ('study_history', 'SELECT id,revision FROM model_studies ORDER BY id'),
            ('run_history', 'SELECT id,NULL FROM workspace_runs ORDER BY id'),
            ('trial_history', 'SELECT id,NULL FROM model_trials ORDER BY id'),
            ('candidate_history', 'SELECT id,NULL FROM model_candidates ORDER BY id'),
            ('model_material', 'SELECT sha256,revision FROM model_materials ORDER BY sha256'),
            ('recipe_material', 'SELECT sha256,recipe_revision FROM workspace_recipe_materials ORDER BY sha256'),
            ('dataset_exposure', 'SELECT id,NULL FROM workspace_exposures ORDER BY id'),
            ('generation_history', 'SELECT id,NULL FROM generation_jobs ORDER BY id'),
            ('grounded_history', 'SELECT id,NULL FROM grounded_jobs ORDER BY id'),
            ('caption_proposal_history', 'SELECT id,NULL FROM caption_proposals ORDER BY id'),
            ('text_proposal_history', 'SELECT id,NULL FROM text_classification_proposals ORDER BY id')):
            for row in self.db.execute(statement):
                self.observe(family, row[0], row[1])
        # These two owners remove the current row on deletion. Their closed
        # successful audit facts retain a known identity, not its lost contents.
        # Keep those identities visible in the global selection report.
        for row in self.db.execute("SELECT action,target_json,details_json FROM access_audit WHERE result='success' AND action IN ('saved_selections.delete','saved_searches.delete') ORDER BY created_at,id"):
            family = 'saved_selection' if row[0] == 'saved_selections.delete' else 'saved_search'
            try:
                identity, details = _json(row[1]), _json(row[2])
                data_codec.identity(identity)
                if type(details) is not dict or set(details) != {'revision', 'retired_sha256'} or type(details['revision']) is not int or details['revision'] < 1:
                    continue
                data_codec.sha(details['retired_sha256'])
            except (WorkbenchError, ValueError, TypeError):
                continue
            key = family, identity
            if key not in self.inventory:
                self.observe(family, identity, details['revision'])
                self.deleted_intents.add(key)
        if len(self.inventory) > MAX_RECORDS:
            raise WorkbenchError('Legacy source exceeds the supported finite inventory.', 'too_large', 413)

    def capture_record(self, identity, key):
        current = Workbench._get(self.reader, identity)
        history = [_json(row[0]) for row in self.db.execute('SELECT snapshot FROM workbench_history WHERE id=%s ORDER BY revision', (identity,))]
        origin = _json(self.db.execute('SELECT provenance_json FROM workbench_records WHERE id=%s', (identity,)).fetchone()[0])
        kind = current['kind']
        if kind == 'text':
            original = self.db.execute('SELECT original_text FROM workbench_records WHERE id=%s', (identity,)).fetchone()[0]
            source = dict(kind=kind, original_text=original)
        elif kind == 'image':
            row = self.db.execute('SELECT * FROM samples WHERE id=%s', (identity,)).fetchone()
            if row is None:
                _missing('The deleted image has no preserved original source row or source geometry.')
            sample = dict(row); sample['annotation'] = _json(sample['annotation'])
            original = self.source.read_catalog('images/' + identity + '/source', MAX_PAYLOAD)
            oriented = self.source.read_catalog('images/' + identity + '/image.png', MAX_PAYLOAD)
            if hashlib.sha256(original).hexdigest() != sample['sha256'] or hashlib.sha256(oriented).hexdigest() != current['content_hash']:
                raise WorkbenchError('Original image bytes changed outside their recorded identity.', 'corrupt_payload', 409)
            source = dict(kind=kind, original=self.raw(key, original, 'original', kind=kind),
                oriented=self.raw(key, oriented, 'oriented', media='image/png', kind=kind), revisions=[sample], deleted=False)
            if sample['revision'] != 1:
                self.issue(key, 'source_history_unavailable', 'Earlier image source revisions were not retained by the legacy catalog.')
                return
        elif kind in ('sequence', 'mesh', 'pointcloud', 'volume'):
            statements = {'sequence': 'SELECT bundle FROM workbench_sequence_assets WHERE id=%s',
                'mesh': 'SELECT bundle FROM workbench_mesh_assets WHERE id=%s',
                'pointcloud': 'SELECT bundle FROM workbench_pointcloud_assets WHERE id=%s',
                'volume': 'SELECT bundle FROM workbench_volume_assets WHERE id=%s'}
            row = self.db.execute(statements[kind], (identity,)).fetchone()
            if row is None:
                _missing('Original immutable BYTEA bundle is missing.')
            raw = bytes(row[0])
            if hashlib.sha256(raw).hexdigest() != current['content_hash']:
                raise WorkbenchError('Original immutable BYTEA identity differs.', 'corrupt_payload', 409)
            source = dict(kind=kind, asset=self.raw(key, raw, 'original', media='application/zip', kind=kind), metadata=copy.deepcopy(current[kind]))
        elif kind in ('audio', 'field_sequence'):
            raw = self._catalog_source(kind, identity)
            if hashlib.sha256(raw).hexdigest() != current['content_hash']:
                raise WorkbenchError('Original scientific/audio source identity differs.', 'corrupt_payload', 409)
            source = dict(kind=kind, asset=self.raw(key, raw, 'original', kind=kind,
                media='audio/wav' if kind == 'audio' else 'application/zip'), metadata=copy.deepcopy(current[kind]))
        else:
            raise WorkbenchError('Unsupported source data kind.', 'unsupported', 409)
        doc = dict(format='workbench_record_v1', origin=origin, source=source, current=current,
            history=history, events=[], audit=self._audit(identity, data_codec.DATA_ACTIONS))
        self.add(dict(family='workbench_record', id=identity, document=doc))
        for parent in current['parents']:
            self.need('workbench_record', parent, key, 'immutable data parent')
        for response in self.db.execute('SELECT id FROM workbench_responses WHERE prompt_id=%s ORDER BY id', (identity,)):
            self.need('workbench_response', response[0], key, 'captured response to selected prompt')
        for preference in self.db.execute('SELECT id FROM workbench_preferences WHERE prompt_id=%s ORDER BY id', (identity,)):
            self.need('workbench_preference', preference[0], key, 'captured preference for selected prompt')
        provenance = origin
        generation = provenance.get('generation')
        if generation is not None:
            self.need('generation_history', generation['job_id'], key, 'exact generating producer')
        for field, family in (('caption_proposal', 'caption_proposal_history'), ('text_classification_proposal', 'text_proposal_history'), ('grounded', 'grounded_history')):
            if field in provenance and isinstance(provenance[field], dict) and 'job_id' in provenance[field]:
                self.need(family, provenance[field]['job_id'], key, 'exact source producer evidence')

    def capture_response(self, identity, key):
        current = Workbench._response(self.reader, identity)
        history = [_json(row[0]) for row in self.db.execute('SELECT snapshot FROM workbench_response_history WHERE id=%s ORDER BY revision', (identity,))]
        self.add(dict(family='workbench_response', id=identity, document=dict(format='workbench_response_v1',
            current=current, history=history, audit=self._audit(identity, data_codec.DATA_ACTIONS))))
        self.need('workbench_record', current['prompt_id'], key, 'exact captured response prompt')

    def capture_preference(self, identity, key):
        from preferences import Preferences
        current = Preferences._get(SimpleNamespace(db=self.db), identity)
        history = [_json(row[0]) for row in self.db.execute('SELECT snapshot FROM workbench_preference_history WHERE id=%s ORDER BY revision', (identity,))]
        self.add(dict(family='workbench_preference', id=identity, document=dict(format='workbench_preference_v1',
            current=current, history=history, audit=self._audit(identity, data_codec.DATA_ACTIONS))))
        self.need('workbench_record', current['prompt_id'], key, 'exact captured preference prompt')
        for response in (current['left_id'], current['right_id']):
            self.need('workbench_response', response, key, 'exact captured preference answer')

    def capture_saved(self, family, identity, key):
        from saved_selections import SavedSelections
        from saved_searches import SavedSearches
        if key in self.deleted_intents:
            self.issue(key, 'intent_history_unavailable', 'A successful legacy deletion retains this identity and retired hash, but its original name and criteria/membership history are unavailable.')
            return
        current = (SavedSelections if family == 'saved_selection' else SavedSearches)._get(SimpleNamespace(db=self.db), identity)
        if family == 'saved_selection':
            for member in current['items']:
                self.need('workbench_record', member['id'], key, 'saved exact membership')
        if current['revision'] != 1:
            self.issue(key, 'intent_history_unavailable', 'Legacy storage retains only the current saved name and criteria/membership, not its earlier revisions.')
            return
        self.add(dict(family=family, id=identity, document=dict(format=data_codec.FAMILIES[family],
            current=current, history=[copy.deepcopy(current)], deleted=False, audit=self._audit(identity, data_codec.DATA_ACTIONS))))

    def capture_definition(self, family, identity, key):
        statement = {'pipeline_graph': 'SELECT document FROM workspace_graphs WHERE id=%s',
            'model_definition': 'SELECT document FROM model_definition_drafts WHERE id=%s',
            'recipe_definition': 'SELECT document FROM workspace_recipe_drafts WHERE id=%s'}[family]
        row = self.db.execute(statement, (identity,)).fetchone()
        if row is None:
            _missing('Selected editable definition is missing.')
        value = material_codec._definition(family, _json(row[0]), self.origin)
        audits = []
        for fact in self._audit(identity, material_codec.AUDIT_ACTIONS):
            try:
                material_codec._definition_audit(family, value, fact, self.origin)
            except WorkbenchError:
                continue
            audits.append(fact)
        if len(audits) != 1:
            _missing('The current editable definition has no unique exact original audit fact.')
        record = dict(family=family, id=key[1], document=dict(format=material_codec.FAMILIES[family],
            origin_catalog_id=self.origin, current=value, revisions=[copy.deepcopy(value)], audit=audits))
        material_codec.decode_records([record]);self.add(record)
        if value['revision'] > 1:
            self.issue(key, 'observed_history_incomplete', 'Only the actual retained current definition and its exact audit are available; earlier definition documents were not stored.', warning=True)
        selector = value.get('source_selector')
        if selector is not None:
            self.snapshot_dependency(selector['project_id'], key)
        if family == 'pipeline_graph':
            # Graph-specific dependency extraction is delegated to the existing
            # graph grammar below rather than inferred from arbitrary JSON.
            for node in value['nodes']:
                if node['type'] == 'release':
                    self.need('dataset_release', node['parameters']['release_id'], key, 'frozen graph input release')
                elif node['type'] == 'input' and value['recipe'] == 'external_recipe':
                    self.snapshot_dependency(node['parameters']['project_id'], key)

    def snapshot_dependency(self, identity, parent):
        row = self.db.execute('SELECT document FROM workspace_projects WHERE id=%s', (identity,)).fetchone()
        if row is None:
            _missing('Required registered project snapshot is missing.')
        saved = decode_retained_snapshot(_json(row[0]));self.snapshot_by_id[identity] = saved
        self.need('project_snapshot', saved['manifest_sha256'], parent, 'exact retained source registration')

    def capture_snapshot(self, sha, key):
        matches = [value for value in self.snapshot_by_id.values() if value['manifest_sha256'] == sha]
        if len(matches) != 1:
            _missing('An exact selected project snapshot is not available in this pinned source.')
        saved = matches[0]
        root = self.source.roots.get(saved['root'])
        if root is None or list(root[1]) != saved['root_identity']:
            _missing('The retained registration has no matching current explicit source-root capability.')
        raw = self.source.read_root(saved['root'], saved['manifest_path'], 65536)
        if hashlib.sha256(raw).hexdigest() != sha or manifest(decode_manifest(raw)) != saved['manifest']:
            raise WorkbenchError('Original registered manifest bytes differ.', 'corrupt_payload', 409)
        blob = self.raw(key, raw, 'project_manifest')
        record = dict(family='project_snapshot', id=key[1], document=dict(format=material_codec.FAMILIES['project_snapshot'],
            origin_catalog_id=self.origin, value=saved, artifacts=material_codec._edges([dict(name=saved['manifest_path'], **blob)], 'project_snapshot'), audit=[]))
        material_codec.decode_records([record]);self.add(record)

    def capture_material(self, family, sha, key):
        statement = ('SELECT document FROM model_materials WHERE sha256=%s' if family == 'model_material'
                     else 'SELECT document FROM workspace_recipe_materials WHERE sha256=%s')
        row = self.db.execute(statement, (sha,)).fetchone()
        if row is None:
            _missing('Required immutable material is missing.')
        value = _json(row[0]);inventory = material_codec._inventory(family, value)
        target = value['ref']['id'] if family == 'model_material' else sha
        action = 'models.publish' if family == 'model_material' else 'recipes.material'
        expected = (dict(revision=value['ref']['revision'], material_sha256=sha) if family == 'model_material'
                    else dict(recipe_id=value['material']['recipe_id'], revision=value['material']['recipe_revision']))
        audits = [fact for fact in self._audit(target, {action}) if fact['details'] == expected]
        record = dict(family=family, id=key[1], document=dict(format=material_codec.FAMILIES[family],
            origin_catalog_id=self.origin, value=value, artifacts=material_codec._edges(inventory, family), audit=audits))
        material_codec.decode_records([record]);self.add(record)
        folder = 'model-materials' if family == 'model_material' else 'workspace-recipe-materials'
        for item in inventory:
            try:
                raw = self.source.read_catalog(folder + '/' + sha + '/' + item['name'], min(MAX_PAYLOAD, max(item['bytes'], 1)))
            except (OSError, WorkbenchError):
                raw = None
            self.intrinsic(key, item, role=item['name'], raw=raw)
        material = value['material']
        if family == 'model_material':
            self.need('model_definition', material['model_definition_id'], key, 'original editable model definition')
            if material['source_selector'] is not None:
                self.snapshot_dependency(material['source_selector']['project_id'], key)
        else:
            self.need('model_material', material['model']['sha256'], key, 'exact composed model material')
            self.need('pipeline_graph', material['recipe_id'], key, 'original editable composition graph')
            for release in material['data']:
                self.need('dataset_release', release['id'], key, 'exact frozen composition data')
            recipe = material['recipe_document']
            raw = self.source.resolve_payload(recipe['sha256'], recipe['bytes'])
            snapshot = _json(raw.decode('utf-8'))
            if snapshot['format'] == 'builtin_recipe_snapshot_v1':
                environment = snapshot['validation']['runtime']
            else:
                execution = snapshot['preflight']['material']
                environment = execution.get('torch_runtime', execution.get('cpu_snapshot', execution['runtime']))
            self.capture_runtime(environment, key)

    def capture_runtime(self, environment, parent):
        from pipeline import digest
        from recipe_process import decode
        sha = digest(environment);key = self.need('runtime_material', sha, parent, 'original measured runtime material')
        if key in self.records:
            return
        descriptor = environment if environment.get('profile') in ('captured_cpu_python_v1', 'managed_torch_python_v1') else None
        raw = self.source.resolve_payload(descriptor['manifest_sha256'], descriptor['manifest_bytes']) if descriptor else None
        decoded = decode(raw) if raw is not None else None
        value = dict(ref=dict(kind='runtime', catalog_id=self.origin, id=sha, sha256=sha), descriptor=descriptor,
            environment=environment if descriptor is None else None, manifest=decoded)
        value = material_codec.decode_runtime_material(value, catalog_id=self.origin)
        inventory = ([dict(name='manifest.json', sha256=descriptor['manifest_sha256'], bytes=descriptor['manifest_bytes'])] +
            [dict(name=item['path'], sha256=item['sha256'], bytes=item['bytes']) for item in decoded['files']]) if descriptor else []
        record = dict(family='runtime_material', id=key[1], document=dict(format=material_codec.FAMILIES['runtime_material'],
            origin_catalog_id=self.origin, value=value, artifacts=material_codec._edges(inventory, 'runtime_material'), audit=[]))
        material_codec.decode_records([record]);self.add(record)
        for item in record['document']['artifacts']:
            self.intrinsic(key, item['blob'], preservation=item['preservation'], role=item['name'], raw=raw if item['name'] == 'manifest.json' else None)

    def capture_study(self, identity, key):
        row = self.db.execute('SELECT document FROM model_studies WHERE id=%s', (identity,)).fetchone()
        if row is None:_missing('Selected Study is missing.')
        study = _json(row[0]);ref = study['policy']
