        doc['revisions'] = [observed_revisions[revision] for revision in sorted(observed_revisions)]
        doc['policies'] = [policies[sha] for sha in sorted(policies)]
        doc['revision_history_complete'] = sorted(observed_revisions) == list(range(1, study['revision'] + 1))
        for trial in study['trial_ids']:
            self.need('trial_history', trial, key, 'immutable Study Trial membership')
        for reservation in reservations:
            self.need('run_history', reservation['run_id'], key, 'spent or reserved scientific attempt')
        candidate_ids = []
        for row in self.db.execute('SELECT id,document FROM model_candidates WHERE study_id=%s ORDER BY id', (identity,)):
            self.need('candidate_history', row[0], key, 'retained scientific candidate')
            candidate_ids.append(row[0]);candidate = _json(row[1]);policy_ref = candidate['policy']
            if policy_ref['sha256'] not in policies:
                policy_row = self.db.execute('SELECT document FROM model_selection_policies WHERE sha256=%s', (policy_ref['sha256'],)).fetchone()
                if policy_row is None:_missing('Candidate lost its exact historical selection policy.')
                policies[policy_ref['sha256']] = dict(ref=policy_ref, policy=_json(policy_row[0]))
        doc['policies'] = [policies[sha] for sha in sorted(policies)]
        targets = {identity, *study['trial_ids'], *candidate_ids, *(item['run_id'] for item in reservations)}
        for target in sorted(targets):
            doc['audit'].extend(self._audit(target, history_codec.OPERATIONS | {'studies.admit', 'studies.approve', 'studies.reconcile', 'studies.candidate_selected', 'studies.lineage.record', 'runs.admit', 'runs.admit_external', 'runs.update', 'runs.reconcile', 'runs.expose_test'}))
        history_codec._audit(doc['audit'])
        self.add(history_codec.envelope('study_history', self.origin, identity, doc))
        if not doc['revision_history_complete']:
            self.issue(key, 'observed_history_incomplete', 'The legacy catalog retained only this Study revision; immutable memberships, policies, Trials and reservations are preserved.', warning=True)

