'use strict';
// Real graph layout/rendering decisions; DOM focus and activation need browser evidence.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const window={};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../static/experiment-graph.js'),'utf8'),{window});
const graph=window.WorkspaceExperimentGraph;
const node=(id,extra={})=>({id,title:'Recorded experiment '+id,recordedAt:'',parent:null,baseline:null,lines:['Ancestry unknown'],...extra});
const a=node('a'),b=node('b',{parent:'a'}),c=node('c',{parent:'b'});
const chain=graph.layout([c,a,b]);
assert.ok(chain.positions.get('a').x<chain.positions.get('b').x);
assert.ok(chain.positions.get('b').x<chain.positions.get('c').x);
assert.throws(()=>graph.layout([node('a',{parent:'c'}),b,c]),/cycle/);
assert.throws(()=>graph.layout([a,a]),/Invalid/);
assert.throws(()=>graph.layout(Array.from({length:101},(_,i)=>node(String(i)))),/100/);
assert.throws(()=>graph.render([a],{zoom:Infinity}),/zoom/);
assert.throws(()=>graph.render([node('x',{lines:['x'.repeat(2001)]})]),/Invalid/);
const roots=graph.render([a,node('d',{recordedAt:'later'})]);
assert.doesNotMatch(roots.html,/<path /,'layout order and timestamps never imply edges');
const baseline=graph.render([a,node('d',{baseline:'a'})]);
assert.equal((baseline.html.match(/class="baseline"/g)||[]).length,1);
assert.doesNotMatch(baseline.html,/class="parent"/);
assert.equal(baseline.positions.get('a').x,baseline.positions.get('d').x,'comparison does not imply derivation depth');
const missing=graph.render([node('b',{parent:'outside-window'})]);
assert.doesNotMatch(missing.html,/<path /,'an unloaded parent cannot become a fabricated graph node');
const escaped=graph.render([node('x" onclick="bad',{title:'<img onerror="bad">',lines:['<script>bad()</script>']})],{selected:'x" onclick="bad',zoom:0.6});
assert.doesNotMatch(escaped.html,/<img|<script| onclick="/);
assert.match(escaped.html,/aria-pressed="true"/);
assert.match(escaped.html,/type="button"/);
assert.match(escaped.html,/tabindex="0"/);
assert.match(escaped.html,/&lt;script&gt;/);
console.log('PASS shared experiment graph: explicit ancestry, cycles, unknown/missing parents, baseline distinction, bounds and escaped button semantics');
