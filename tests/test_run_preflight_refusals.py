        before = case.counts()
        # Actual production preparation observes the fixture's unavailable runtime.
        with patch('subprocess.Popen', side_effect=AssertionError('Preflight cannot execute a child')):
            value = case.client.call('graphs.preflight_external', {'graph_id': graph['id'], 'revision': 1})
            self.assertGreaterEqual(value['status'], 400)
            report = value['result']['preflight_report']
            self.assertIsNone(report['material_sha256']); self.assertEqual(report['admission'], 'not_reserved')
            for version in (1, 2, 3):
                status, old = case.http('graphs.preflight_external', {'graph_id': graph['id'], 'revision': 1},
                                       version=version, token=case.owner.token)
                self.assertEqual(status, value['status']); self.assertEqual(old['code'], value['result']['code'])
                self.assertNotIn('preflight_report', old)
            status, old = case.http('graphs.preflight_external', {'graph_id': graph['id'], 'revision': 1},
                                    selected=False, token=case.owner.token)
            self.assertEqual(status, value['status']); self.assertNotIn('preflight_report', old)
            stderr = io.StringIO()
            with patch.object(api.AgentClient, 'from_config', return_value=case.client), redirect_stderr(stderr):
                exit_code = project_cli.main(['--config', '/unused', 'preflight', '--graph-id', graph['id'], '--revision', '1'])
            self.assertEqual(exit_code, 1)
            self.assertEqual(json.loads(stderr.getvalue())['preflight_report'], report)
            with patch.object(pipeline.recipe_contract, 'prepare') as prepare:
                status, denied = case.http('graphs.preflight_external', {'graph_id': graph['id'], 'revision': 1},
                                           token='x' * 32)
                self.assertEqual(status, 401); self.assertNotIn('preflight_report', denied)
                prepare.assert_not_called()
        self.assertEqual(case.counts(), before)


