class PreflightRefusalTests(unittest.TestCase):
    def setUp(self):
        self.fixture = prior.PreflightReportTests('runTest')
        self.fixture.setUp()
        self.arguments = {'graph_id': 'a' * 32, 'revision': 2}

    def refusal(self, code='unavailable', status=409):
        error = WorkbenchError('Private producer detail must not enter report', code, status)
        report = pipeline._external_preflight_refusal('b' * 32, 'a' * 32, 2, error)
        return {'status': status, 'result': {'code': code, 'error': str(error), 'preflight_report': report}}

    @staticmethod
    def rehash(report):
        report['sha256'] = pipeline.digest({k: v for k, v in report.items() if k != 'sha256'})

    def test_installed_contract_hashes_and_legacy_projection_are_unchanged(self):
        # Frozen from the verified baseline360bb, not generated by this implementation.
        hashes = {1: '81515fd903aefd3ab717a8a9b7cfb937726a312b1fa4808bec8a06ae03094125',
                  2: '7b287616c67d154615980c239c418f54764f7ffd8fef2430d13d582dc8319951',
                  3: 'ed0796b3c889f042966ec9308d9c5aebfc13031b668d42654de98dd892f5c96c'}
        for version, sha in hashes.items():
            self.assertEqual(api.contract('graphs.preflight_external', version)['sha256'], sha)
        self.assertEqual(api.discovery()['digest'], 'cb070a69ebd35b48e4f95a57ca01647c75bd7567521429e49efc3a3a1daebae8')

    def test_refusals_preserve_typed_outcome_and_only_request_provenance(self):
        for code, state in (('invalid', 'invalid'), ('unsupported', 'unsupported'),
                            ('unavailable', 'blocked'), ('stale', 'blocked'), ('storage', 'blocked')):
            value = self.refusal(code); report = value['result']['preflight_report']
            self.assertEqual(api.validate_output('graphs.preflight_external', value), value)
            self.assertEqual(report['state'], state)
            self.assertEqual(report['refusal'], {'code': code, 'status': 409})
            self.assertIsNone(report['material_sha256']); self.assertIsNone(report['execution_sha256'])
            self.assertEqual(report['admission'], 'not_reserved')
            self.assertLess(len(json.dumps(report).encode()), 8192)
            self.assertLessEqual(len(report['checks']), 16)
            self.assertFalse(any(row['state'] == 'checked' for row in report['checks']))
            self.assertNotIn('Private producer detail', json.dumps(report))
            self.assertTrue(any(row['code'] == 'runtime_ready_go' and row['state'] == 'deferred'
                                for row in report['checks']))

    def test_domain_preserves_original_error_and_does_not_reprepare_or_publish(self):
        graph, owner, prepared = self.fixture.domain_owner()
        owner.db = SimpleNamespace(dataset_id='b' * 32)
        for version in (None, 1, 2, 3, 4):
            error = WorkbenchError('Runtime unavailable', 'unavailable', 409)
            with patch.object(pipeline.recipe_contract, 'prepare', side_effect=error) as prepare:
                with self.assertRaises(WorkbenchError) as caught:
                    pipeline.Pipelines.preflight_external(owner, graph['id'], 2, contract_version=version)
            self.assertIs(caught.exception, error); self.assertEqual(prepare.call_count, 1)
            self.assertEqual(getattr(error, 'preflight_report', None) is not None, version == 4)
        with patch.object(pipeline.recipe_contract, 'prepare', return_value=(prepared, {})):
            result = pipeline.Pipelines.preflight_external(owner, graph['id'], 2, contract_version=4)
        # Use the consistent material fixture for selected schema/hash validation.
        report = pipeline._external_preflight_report(self.fixture.graph, self.fixture.prepared, version=2)
        value = {'status': 200, 'result': dict(self.fixture.prepared, preflight_report=report)}
        api.validate_output('graphs.preflight_external', value)
        self.assertEqual(result['preflight_report']['format'], 'external_preflight_report_v2')
        self.assertIsNone(report['refusal'])

    def test_storage_owner_and_graph_drift_do_not_reuse_checked_material(self):
        graph, owner, prepared = self.fixture.domain_owner(); owner.db = SimpleNamespace(dataset_id='b' * 32)
        prepared = copy.deepcopy(prepared)
        prepared['material']['resources']['profile'] = pipeline.recipe_contract.LARGE_OUTPUT_PROFILE
        owner.dataset.runs = Mock()
        owner.dataset.runs._check_external_storage.side_effect = WorkbenchError('Disk full', 'unavailable', 409)
        with patch.object(pipeline.recipe_contract, 'prepare', return_value=(prepared, {})):
            with self.assertRaises(WorkbenchError) as caught:
                pipeline.Pipelines.preflight_external(owner, graph['id'], 2, contract_version=4)
        report = caught.exception.preflight_report
        self.assertEqual((report['checks'][0]['owner'], report['checks'][0]['code']), ('runs', 'storage_capacity'))
        self.assertIsNone(report['material_sha256'])
        owner.get.side_effect = [graph, dict(graph, revision=3)]
        prepared['material']['resources'].pop('profile')
        with patch.object(pipeline.recipe_contract, 'prepare', return_value=(prepared, {})):
            with self.assertRaises(WorkbenchError) as caught:
                pipeline.Pipelines.preflight_external(owner, graph['id'], 2, contract_version=4)
        report = caught.exception.preflight_report
        self.assertEqual(report['graph_revision'], 2)
        self.assertEqual(report['refusal']['code'], 'stale')
        self.assertFalse(any(row['state'] == 'checked' for row in report['checks']))

    def test_authorization_and_early_refusals_have_no_report_or_extra_graph_read(self):
        graph, owner, _ = self.fixture.domain_owner()
        owner.access.require.side_effect = access.AccessError('Denied')
        with self.assertRaises(access.AccessError):
            pipeline.Pipelines.preflight_external(owner, graph['id'], 2, contract_version=4)
        owner.get.assert_not_called()
        for status in (400, 401, 403, 409, 503):
            api.validate_output('graphs.preflight_external', {'status': status,
                'result': {'error': 'Bare early error', 'code': 'forbidden'}}, 4)

    def test_consumers_reject_forged_proof_status_duplicates_bounds_and_hash(self):
        mutations = (lambda r: r.update(material_sha256='c' * 64),
                     lambda r: r.update(execution_sha256='c' * 64),
                     lambda r: r.update(state='prepared'),
                     lambda r: r['refusal'].update(status=503),
                     lambda r: r['checks'][0].update(state='checked'),
                     lambda r: r['checks'].append(copy.deepcopy(r['checks'][0])),
                     lambda r: r['checks'][0].update(detail='x' * 241),
                     lambda r: r['checks'][0].update(evidence_sha256='d' * 64),
                     lambda r: r['checks'][0].update(owner='runs'),
                     lambda r: r['checks'][0].update(phase='publication'),
                     lambda r: r['checks'][0].update(code='storage_capacity'),
                     lambda r: r['checks'][0].update(boundary='A fabricated verified runtime boundary'),
                     lambda r: r['checks'].pop(),
                     lambda r: r.update(sha256='e' * 64))
        for index, mutate in enumerate(mutations):
            value = self.refusal(); report = value['result']['preflight_report']; mutate(report)
            if index != len(mutations)-1: self.rehash(report)
            with self.subTest(index=index), self.assertRaises(api.AgentAPIError):
                api.validate_output('graphs.preflight_external', value, 4)

    def test_client_correlates_error_report_without_retry_and_wrappers_retain_it(self):
        client = api.AgentClient('http://127.0.0.1:12345', 'k' * 32, 'b' * 32)
        client._ready = True; client._selected = {'graphs.preflight_external': 4}
        value = self.refusal(); client._request = Mock(return_value=value)
        self.assertEqual(client.call('graphs.preflight_external', self.arguments), value)
        for arguments in ({'graph_id': 'c' * 32, 'revision': 2}, dict(self.arguments, revision=3)):
            client._request.reset_mock()
            with self.assertRaises(api.AgentAPIError): client.call('graphs.preflight_external', arguments)
            self.assertEqual(client._request.call_count, 1)
        client.catalog_id = 'c' * 32
        with self.assertRaises(api.AgentAPIError): client.call('graphs.preflight_external', self.arguments)
        client.catalog_id = 'b' * 32
        with self.assertRaises(api.AgentAPIError) as caught:
            WorkflowClient(client).submission_manifest('a' * 32, 2, approval_id='d' * 32, request_key='request123')
        self.assertEqual(caught.exception.preflight_report, value['result']['preflight_report'])
        stderr = io.StringIO()
        with patch.object(api.AgentClient, 'from_config', return_value=client), redirect_stderr(stderr):
            result = project_cli.main(['--config', '/unused', 'preflight', '--graph-id', 'a' * 32, '--revision', '2'])
        self.assertEqual(result, 1)
        self.assertEqual(json.loads(stderr.getvalue())['preflight_report'], value['result']['preflight_report'])

    @contextmanager
    def transport(self, value):
        class Handler(BaseHTTPRequestHandler):
            def do_POST(self):
                raw = json.dumps(value['result']).encode(); self.send_response(value['status'])
                self.send_header('Content-Type', 'application/json'); self.send_header('Content-Length', str(len(raw)))
                self.end_headers(); self.wfile.write(raw)
            def log_message(self, *args): pass
        server = ThreadingHTTPServer(('127.0.0.1', 0), Handler)
        thread = threading.Thread(target=server.serve_forever); thread.start()
        try: yield 'http://127.0.0.1:' + str(server.server_port)
        finally: server.shutdown(); server.server_close(); thread.join()

    def test_real_http_error_normalization_preserves_only_selected_report_and_redacts(self):
        value = self.refusal(); value['result'].update(unrelated='discard', error='k' * 32)
        with self.transport(value) as base:
            client = api.AgentClient(base, 'k' * 32, 'b' * 32)
            client._ready = True
            for version in (3, 4):
                client._selected = {'graphs.preflight_external': version}
                result = client.call('graphs.preflight_external', self.arguments)['result']
                self.assertEqual('preflight_report' in result, version == 4)
                self.assertNotIn('unrelated', result); self.assertEqual(result['error'], '[redacted]')
            report = value['result']['preflight_report']
            value['result']['preflight_report'] = None
            with self.assertRaises(api.AgentAPIError):
                client.call('graphs.preflight_external', self.arguments)
            value['result']['preflight_report'] = report
            value['result']['preflight_report']['checks'][0]['detail'] = 'k' * 32
            with self.assertRaises(api.AgentAPIError) as caught:
                client.call('graphs.preflight_external', self.arguments)
            self.assertNotIn('k' * 32, str(caught.exception))


